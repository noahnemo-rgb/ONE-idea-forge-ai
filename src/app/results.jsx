import React, { useEffect, useState } from "react";
import {
  View,
  Text,
  ScrollView,
  TouchableOpacity,
  ActivityIndicator,
  Share,
} from "react-native";
import { StatusBar } from "expo-status-bar";
import { useSafeAreaInsets } from "react-native-safe-area-context";
import { useLocalSearchParams, useRouter } from "expo-router";
import {
  ArrowLeft,
  Bookmark,
  Share2,
  ExternalLink,
  CheckCircle2,
  AlertCircle,
  Copy,
  Clipboard as ClipboardIcon,
} from "lucide-react-native";
import { useTheme } from "@/contexts/ThemeContext";
import { useSubscription } from "@/hooks/useSubscription";
import { useMutation } from "@tanstack/react-query";
import * as Clipboard from "expo-clipboard";
import { Alert } from "react-native";

export default function ResultsScreen() {
  const insets = useSafeAreaInsets();
  const theme = useTheme();
  const router = useRouter();
  const { prompt, trending } = useLocalSearchParams();
  const { isPro } = useSubscription();
  const [ideas, setIdeas] = useState([]);
  const [error, setError] = useState(null);

  const generateMutation = useMutation({
    mutationFn: async (data) => {
      const response = await fetch("/api/generate", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          ...data,
          isPro, // Pass pro status to backend to unlock premium models
        }),
      });
      if (!response.ok) {
        if (response.status === 403)
          throw new Error(
            "Generation limit reached. Upgrade to Pro for unlimited sparks!",
          );
        throw new Error("Failed to generate ideas");
      }
      return response.json();
    },
    onSuccess: (data) => {
      setIdeas(data.ideas);
    },
    onError: (err) => {
      setError(err.message);
    },
  });

  useEffect(() => {
    if (prompt) {
      generateMutation.mutate({ prompt, trending: trending === "true" });
    }
  }, [prompt]);

  const handleShare = async (idea) => {
    try {
      await Share.share({
        message: `Check out this app idea from IdeaForge: ${idea.title}\n\n${idea.description}`,
      });
    } catch (error) {
      console.error(error);
    }
  };

  const handleExportSpec = async (idea) => {
    const spec = `
# IdeaForge Spec: ${idea.title}
Generated on: ${new Date().toLocaleDateString()}
Model Source: ${idea.model_source || "IdeaForge AI Engine"}

## 1. Overview
${idea.description}

## 2. Target Audience
${idea.target_audience}

## 3. Key Features
${idea.key_features?.map((f) => `- ${f}`).join("\n")}

## 4. Market Validation Scores
${Object.entries(idea.scores || {})
  .map(([key, val]) => `- ${key.replace("_", " ").toUpperCase()}: ${val}/10`)
  .join("\n")}

## 5. Suggested Tech Stack
- **Frontend**: React / Next.js (Web), React Native / Expo (Mobile)
- **Backend**: Node.js / PostgreSQL
- **Database**: PostgreSQL
- **Styling**: Tailwind CSS / NativeWind
- **AI Integration**: OpenAI / Anthropic / Gemini

## 6. Build Instructions
1. **Setup**: Initialize a new project using your preferred framework.
2. **Database Schema**: Create tables for users, ${idea.title.toLowerCase().replace(/\s+/g, "_")}, and core features.
3. **Core Logic**: Implement the ${idea.key_features?.[0] || "primary feature"} first.
4. **UI/UX**: Focus on a clean, user-centric design matching the target audience.
5. **Deployment**: Deploy to Vercel (Web) or App Store/Play Store (Mobile).

---
Generated by IdeaForge - Turn your sparks into validated startups.
    `;

    await Clipboard.setStringAsync(spec);
    Alert.alert(
      "Spec Copied!",
      "The full idea specification has been copied to your clipboard as Markdown.",
    );
  };

  const handleCopyIdea = async (idea) => {
    const text = `${idea.title}\n\n${idea.description}\n\nTarget Audience: ${idea.target_audience}\n\nKey Features:\n${idea.key_features?.map((f) => `- ${f}`).join("\n")}`;
    await Clipboard.setStringAsync(text);
    Alert.alert(
      "Idea Copied!",
      "The idea details have been copied to your clipboard.",
    );
  };

  const getScoreColor = (score) => {
    if (score >= 8) return "#4CAF50";
    if (score >= 5) return "#FF9800";
    return "#F44336";
  };

  if (generateMutation.isLoading) {
    return (
      <View
        style={{
          flex: 1,
          backgroundColor: theme.colors.background,
          justifyContent: "center",
          alignItems: "center",
        }}
      >
        <ActivityIndicator size="large" color={theme.colors.primary} />
        <Text
          style={{
            marginTop: 20,
            color: theme.colors.textSecondary,
            fontSize: 16,
          }}
        >
          Forging your ideas...
        </Text>
      </View>
    );
  }

  if (error) {
    return (
      <View
        style={{
          flex: 1,
          backgroundColor: theme.colors.background,
          justifyContent: "center",
          alignItems: "center",
          padding: 40,
        }}
      >
        <AlertCircle size={48} color="#F44336" />
        <Text
          style={{
            marginTop: 20,
            color: theme.colors.text,
            fontSize: 18,
            fontWeight: "600",
            textAlign: "center",
          }}
        >
          Something went wrong
        </Text>
        <Text
          style={{
            marginTop: 10,
            color: theme.colors.textSecondary,
            textAlign: "center",
          }}
        >
          {error}
        </Text>
        <TouchableOpacity
          onPress={() => router.back()}
          style={{
            marginTop: 30,
            backgroundColor: theme.colors.primary,
            paddingHorizontal: 24,
            paddingVertical: 12,
            borderRadius: 12,
          }}
        >
          <Text style={{ color: "white", fontWeight: "600" }}>Go Back</Text>
        </TouchableOpacity>
      </View>
    );
  }

  return (
    <View style={{ flex: 1, backgroundColor: theme.colors.background }}>
      <StatusBar style={theme.colors.statusBarStyle} />

      {/* Header */}
      <View
        style={{
          paddingTop: insets.top + 10,
          paddingHorizontal: 20,
          paddingBottom: 15,
          flexDirection: "row",
          alignItems: "center",
          borderBottomWidth: 1,
          borderBottomColor: theme.colors.border,
        }}
      >
        <TouchableOpacity onPress={() => router.back()} style={{ padding: 8 }}>
          <ArrowLeft size={24} color={theme.colors.text} />
        </TouchableOpacity>
        <Text
          style={{
            flex: 1,
            fontSize: 18,
            fontWeight: "700",
            color: theme.colors.text,
            marginLeft: 10,
          }}
        >
          Results
        </Text>
      </View>

      <ScrollView
        contentContainerStyle={{
          padding: 20,
          paddingBottom: insets.bottom + 40,
        }}
        showsVerticalScrollIndicator={false}
      >
        <View
          style={{
            flexDirection: "row",
            justifyContent: "space-between",
            alignItems: "center",
            marginBottom: 20,
          }}
        >
          <Text
            style={{
              fontSize: 14,
              color: theme.colors.textSecondary,
            }}
          >
            Generated {ideas.length} ideas for: "{prompt}"
          </Text>
          {isPro && (
            <View
              style={{
                backgroundColor: theme.colors.primary + "20",
                paddingHorizontal: 8,
                paddingVertical: 4,
                borderRadius: 8,
              }}
            >
              <Text
                style={{
                  color: theme.colors.primary,
                  fontSize: 10,
                  fontWeight: "700",
                }}
              >
                PREMIUM MODELS ACTIVE
              </Text>
            </View>
          )}
        </View>

        {ideas.map((idea, index) => (
          <View
            key={index}
            style={{
              backgroundColor: theme.colors.surface,
              borderRadius: 24,
              padding: 24,
              marginBottom: 24,
              borderWidth: 1,
              borderColor: theme.colors.border,
              shadowColor: "#000",
              shadowOffset: { width: 0, height: 4 },
              shadowOpacity: 0.05,
              shadowRadius: 10,
              elevation: 2,
            }}
          >
            <View
              style={{
                flexDirection: "row",
                justifyContent: "space-between",
                alignItems: "flex-start",
                marginBottom: 16,
              }}
            >
              <View style={{ flex: 1 }}>
                <Text
                  style={{
                    fontSize: 22,
                    fontWeight: "700",
                    color: theme.colors.text,
                    marginBottom: 4,
                  }}
                >
                  {idea.title}
                </Text>
                <Text
                  style={{
                    fontSize: 14,
                    color: theme.colors.primary,
                    fontWeight: "600",
                  }}
                >
                  {idea.model_source || "AI Engine"}
                </Text>
              </View>
              <View style={{ flexDirection: "row", gap: 12 }}>
                <TouchableOpacity
                  onPress={() => handleCopyIdea(idea)}
                  style={{ padding: 4 }}
                >
                  <ClipboardIcon size={22} color={theme.colors.textSecondary} />
                </TouchableOpacity>
                <TouchableOpacity style={{ padding: 4 }}>
                  <Bookmark size={22} color={theme.colors.textSecondary} />
                </TouchableOpacity>
                <TouchableOpacity
                  onPress={() => handleShare(idea)}
                  style={{ padding: 4 }}
                >
                  <Share2 size={22} color={theme.colors.textSecondary} />
                </TouchableOpacity>
              </View>
            </View>

            <Text
              style={{
                fontSize: 16,
                color: theme.colors.textSecondary,
                lineHeight: 24,
                marginBottom: 20,
              }}
            >
              {idea.description}
            </Text>

            {/* Scores */}
            <View style={{ flexDirection: "row", gap: 12, marginBottom: 24 }}>
              {Object.entries(idea.scores || {}).map(([key, val]) => (
                <View
                  key={key}
                  style={{
                    flex: 1,
                    backgroundColor: theme.colors.background,
                    padding: 12,
                    borderRadius: 16,
                    alignItems: "center",
                    borderWidth: 1,
                    borderColor: theme.colors.border,
                  }}
                >
                  <Text
                    style={{
                      fontSize: 18,
                      fontWeight: "700",
                      color: getScoreColor(val),
                    }}
                  >
                    {val}
                  </Text>
                  <Text
                    style={{
                      fontSize: 10,
                      color: theme.colors.textTertiary,
                      textTransform: "uppercase",
                      marginTop: 4,
                      textAlign: "center",
                    }}
                  >
                    {key.replace("_", " ")}
                  </Text>
                </View>
              ))}
            </View>

            {/* Details */}
            <View style={{ gap: 16 }}>
              <View>
                <Text
                  style={{
                    fontSize: 14,
                    fontWeight: "700",
                    color: theme.colors.text,
                    marginBottom: 4,
                  }}
                >
                  Target Audience
                </Text>
                <Text
                  style={{ fontSize: 14, color: theme.colors.textSecondary }}
                >
                  {idea.target_audience}
                </Text>
              </View>
              <View>
                <Text
                  style={{
                    fontSize: 14,
                    fontWeight: "700",
                    color: theme.colors.text,
                    marginBottom: 4,
                  }}
                >
                  Key Features
                </Text>
                <View style={{ gap: 4 }}>
                  {idea.key_features?.map((f, i) => (
                    <View
                      key={i}
                      style={{ flexDirection: "row", alignItems: "center" }}
                    >
                      <CheckCircle2
                        size={14}
                        color={theme.colors.primary}
                        style={{ marginRight: 8 }}
                      />
                      <Text
                        style={{
                          fontSize: 14,
                          color: theme.colors.textSecondary,
                        }}
                      >
                        {f}
                      </Text>
                    </View>
                  ))}
                </View>
              </View>
            </View>

            <TouchableOpacity
              onPress={() => handleExportSpec(idea)}
              style={{
                marginTop: 24,
                backgroundColor: theme.colors.buttonSecondary,
                paddingVertical: 14,
                borderRadius: 16,
                flexDirection: "row",
                justifyContent: "center",
                alignItems: "center",
              }}
            >
              <Copy
                size={18}
                color={theme.colors.primary}
                style={{ marginRight: 8 }}
              />
              <Text style={{ color: theme.colors.primary, fontWeight: "600" }}>
                Copy Spec Document
              </Text>
            </TouchableOpacity>
          </View>
        ))}
      </ScrollView>
    </View>
  );
}
